@pytest.mark.live_cms
@pytest.mark.live_historical
@pytest.mark.parametrize("fiscal_year", (2014, 2015, 2016, 2017, 2018))
def test_official_change_set_matches_recorded_ledger(
    fiscal_year: int,
    fresh_cache: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    post = resolve_icd9_to_icd10_cm_mappings(
        (fiscal_year,),
        corrections_through_fiscal_year=2018,
        cache_dir=fresh_cache,
    )[fiscal_year]
    clear_resolution_memory_cache()
    monkeypatch.setattr(
        "cms_icd.resolution._common_ancestor",
        _pre_fix_common_ancestor,
    )
    pre = resolve_icd9_to_icd10_cm_mappings(
        (fiscal_year,),
        corrections_through_fiscal_year=2018,
        cache_dir=fresh_cache,
    )[fiscal_year]
    clear_resolution_memory_cache()

    changed = {
        source
        for source in post
        if (pre[source].status, pre[source].target_codes, pre[source].reason)
        != (post[source].status, post[source].target_codes, post[source].reason)
    }
    expected = EXPECTED_CHANGED[fiscal_year]
    assert changed == expected, (
        f"FY{fiscal_year}: changed sources {sorted(changed)} do not match the "
        f"recorded ledger {sorted(expected)}. If CMS changed the official "
        "materials, review the difference and deliberately update the ledger."
    )
    for source in changed:
        before, after = pre[source], post[source]
        assert after.status is ICDMappingStatus.UNMAPPABLE
        assert after.reason in {
            ICDMappingReason.DIVERGENT_ALTERNATIVES,
            ICDMappingReason.DIVERGENT_SCENARIOS,
        }
        assert after.target_codes == ()
        if before.status is ICDMappingStatus.MAPPED:
            assert any("-" in code for code in before.target_codes)
        else:
            assert before.reason is ICDMappingReason.DIVERGENT_SCENARIOS
            assert before.target_codes == ()
    for resolution in post.values():
        if resolution.status is ICDMappingStatus.MAPPED:
            assert all("-" not in code for code in resolution.target_codes)
