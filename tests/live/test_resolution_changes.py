"""Live record of official GEM sources whose resolution changed by issue 1.

Issue 1: https://github.com/ipolharvard/cms-icd/issues/1

Before the fix, ``_common_ancestor`` returned the name of any shared tabular
ancestor node, so a source whose official alternatives span several
3-character categories within one tabular section resolved ``MAPPED`` with
the section's range string (for example ``I10-I15``) as an invalid target
code. After the fix, chapter and section ancestors yield no code and the
affected sources resolve ``UNMAPPABLE``.

For every fiscal year FY2014--FY2018, this check resolves the official
corrected diagnosis GEMs once with the fixed resolver and once with the
pre-fix ancestor logic, then asserts that the set of sources whose
(status, target_codes, reason) changed matches the recorded ledger below and
that every change has the expected shape:

* post-fix: ``UNMAPPABLE`` with ``DIVERGENT_ALTERNATIVES`` (simple path) or
  ``DIVERGENT_SCENARIOS`` (scenario paths) and no target codes;
* pre-fix: ``MAPPED`` with at least one range-string target, or already
  ``UNMAPPABLE`` with the divergent-scenarios reason (the reason changed
  because the simple path is now refused first);
* no post-fix ``MAPPED`` resolution contains a range-string target.

The ledger was recorded on 2026-08-29 from the official CMS artifacts
(FY2014--FY2018 GEM files and ICD-10-CM tabular files). If CMS changes those
materials, review the difference and deliberately update the ledger.
"""

